//imprimir todos os numeros pares de 2 a 20
#include <iostream>
using namespace std;
int main()
{
    //estrutura de repetição com indice começando em 2 e somando +1(2xi++) duas vezes até 20 gerando todos os pares
    for(int i=2;i<=20;i++){
        cout<<" "<<i;
        i++;
    }
    

    return 0;
}